function [k, alpha] = ituP838(fGHz, pol)
%ITUP838  Specific rain attenuation coefficients, ITU-R P.838-3.
%   [k, alpha] = ituP838(fGHz, pol) returns k and alpha for gamma = k * R^alpha (dB/km),
%   R in mm/h, f in GHz (1-1000), pol = 'V' or 'H'.
%   Check values (P.838-3 Table 5): 20 GHz H -> 0.09164, 1.0568; 30 GHz V -> 0.2291, 0.9129.

if nargin < 2, pol = 'V'; end
x = log10(fGHz);
if upper(pol(1)) == 'H'
    ka = [-5.33980 -0.35351 -0.23789 -0.94158];
    kb = [-0.10008  1.26970  0.86036  0.64552];
    kc = [ 1.13098  0.45400  0.15354  0.16817];
    km = -0.18961; kk = 0.71147;
    aa = [-0.14318  0.29591  0.32177 -5.37610 16.1721];
    ab = [ 1.82442  0.77564  0.63773 -0.96230 -3.29980];
    ac = [-0.55187  0.19822  0.13164  1.47828  3.43990];
    am = 0.67849;  ak = -1.95537;
else
    ka = [-3.80595 -3.44965 -0.39902  0.50167];
    kb = [ 0.56934 -0.22911  0.73042  1.07319];
    kc = [ 0.81061  0.51059  0.11899  0.27195];
    km = -0.16398; kk = 0.63297;
    aa = [-0.07771  0.56727 -0.20238 -48.2991 48.5833];
    ab = [ 2.33840  0.95545  1.14520  0.791669 0.791459];
    ac = [-0.76284  0.54039  0.26809  0.116226 0.116479];
    am = -0.053739; ak = 0.83433;
end
k = 10.^(sum(ka(:) .* exp(-((x - kb(:)) ./ kc(:)).^2), 1) + km * x + kk);
alpha = sum(aa(:) .* exp(-((x - ab(:)) ./ ac(:)).^2), 1) + am * x + ak;
end
